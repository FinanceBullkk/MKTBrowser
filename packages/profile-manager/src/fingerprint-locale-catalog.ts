/**
 * The locale catalogue: locale, languages, country and the timezones that country really uses.
 *
 * Split out of `fingerprint.ts` on 18 September 2026 without changing a value. Same reason as the
 * device catalogue - six hundred lines of data in the middle of the code that reads it.
 *
 * Coherence is the whole point: a locale group is only useful if its timezones belong to its
 * country, because a mismatch between the two is exactly what a detector looks for.
 */

// ─────────────────────────────────────────────────────────────────────────
// Locale groups — geographically coherent locale + timezones + country.
// ─────────────────────────────────────────────────────────────────────────

